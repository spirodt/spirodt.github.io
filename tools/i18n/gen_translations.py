"""
Ги генерира германските и албанските преводи за веб страната.

Извор:  src/SpiroPortfolio/Content/translations.tsv   (англиски <TAB> германски <TAB> албански)
Излез:  src/SpiroPortfolio/Content/Translations.g.cs

Македонскиот и англискиот остануваат во SiteContent.cs / компонентите како досега;
DE и SQ се бараат по англискиот текст. Ако превод недостасува, се прикажува англискиот.

Употреба:  python tools/i18n/gen_translations.py            (генерирај)
           python tools/i18n/gen_translations.py --check    (листа на текстови без превод)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2] / "src/SpiroPortfolio"
TSV = ROOT / "Content/translations.tsv"
OUT = ROOT / "Content/Translations.g.cs"


def load() -> dict[str, tuple[str, str]]:
    rows = {}
    for n, line in enumerate(TSV.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            sys.exit(f"translations.tsv:{n}: очекувам 3 колони (EN, DE, SQ), најдов {len(parts)}")
        rows[parts[0]] = (parts[1], parts[2])
    return rows


def english_texts() -> set[str]:
    """Сите англиски текстови од new("мк", "en") / new Loc(...) / T("мк", "en")."""
    pat = re.compile(r'(?:new(?:\s+Loc)?|T)\(\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\s*\)', re.S)
    found = set()
    for f in list(ROOT.rglob("*.cs")) + list(ROOT.rglob("*.razor")):
        if "obj" in f.parts or "bin" in f.parts or f == OUT:
            continue
        for mk, en in pat.findall(f.read_text(encoding="utf-8")):
            if en.strip() and en != mk:
                found.add(en.encode().decode("unicode_escape") if "\\" in en else en)
    return found


def cs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    rows = load()
    missing = sorted(english_texts() - rows.keys())
    if "--check" in sys.argv:
        print(f"{len(rows)} преводи; без превод: {len(missing)}")
        for m in missing:
            print("  -", m)
        sys.exit(1 if missing else 0)

    lines = [
        "// <auto-generated> од tools/i18n/gen_translations.py — НЕ го менувај рачно, менувај translations.tsv </auto-generated>",
        "namespace SpiroPortfolio.Content;",
        "",
        "public static class Translations",
        "{",
        "    /// <summary>Англиски текст → (германски, албански).</summary>",
        "    public static readonly IReadOnlyDictionary<string, (string De, string Sq)> ByEnglish =",
        "        new Dictionary<string, (string De, string Sq)>(StringComparer.Ordinal)",
        "        {",
    ]
    for en, (de, sq) in rows.items():
        lines.append(f"            [{cs(en)}] = ({cs(de)}, {cs(sq)}),")
    lines += ["        };", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"✓ {OUT.name}: {len(rows)} преводи" + (f"  (без превод: {len(missing)} — види --check)" if missing else ""))


if __name__ == "__main__":
    main()
